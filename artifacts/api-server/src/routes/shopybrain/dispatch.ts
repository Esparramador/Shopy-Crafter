export const BRAIN_ACTIONS: readonly string[] = Object.keys(RUNNERS);

export async function dispatchBrainAction(ctx: BrainActionCtx): Promise<BrainActionOutcome> {
  const run = Object.prototype.hasOwnProperty.call(RUNNERS, ctx.action) ? RUNNERS[ctx.action] : undefined;
  return run ? run(ctx) : NOT_HANDLED;
}

