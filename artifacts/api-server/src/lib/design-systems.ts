// ─── Helpers ─────────────────────────────────────────────────────────────────

export function getDesignSystemById(id: string): DesignSystem | undefined {
  return DESIGN_SYSTEMS.find(ds => ds.id === id);
}

export function getDesignSystemsByCategory(category: string): DesignSystem[] {
  return DESIGN_SYSTEMS.filter(ds => ds.category === category);
}

export function searchDesignSystems(query: string): DesignSystem[] {
  const q = query.toLowerCase();
  return DESIGN_SYSTEMS.filter(ds =>
    ds.name.toLowerCase().includes(q) ||
    ds.category.toLowerCase().includes(q) ||
    ds.toneWords.some(t => t.toLowerCase().includes(q)) ||
    ds.designLanguage.toLowerCase().includes(q)
  );
}

